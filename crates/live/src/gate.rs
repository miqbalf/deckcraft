//! The command gate while editing live. Every registered command id is in exactly one table:
//!
//! - [`FREE`]: changes what the room shares (text, shape geometry and look, shapes, z-order,
//!   slides); runs now and is shared as free writes.
//! - [`LOCAL`]: changes nothing shared (selection, navigation, view, find, slide show, export,
//!   playback, queries, other windows and files).
//! - [`HISTORY`]: `edit.undo` and `edit.redo`, owned by the live layer.
//! - [`NOT_YET`]: shares something M1 does not (design, masters, animations, comments, tables,
//!   charts, SmartArt, grouping, sections, guides, picture adjustments, save and revert, which
//!   the worker does); refused with [`NOT_YET_TEXT`].
//! - [`MEDIA`]: adds pictures, video or audio (Ruling D14); refused with [`MEDIA_TEXT`].
//!
//! An id in no table (a command added later) is refused like [`NOT_YET`]. A test checks the
//! tables against the engine's command list. Running an unshared command anyway (bypassing the
//! gate) is caught after the fact by the safety net ([`crate::net`]).

/// Why a command that is not shared yet is refused.
pub const NOT_YET_TEXT: &str = "Not available while editing live yet";
/// Why a command that adds media is refused (Ruling D14).
pub const MEDIA_TEXT: &str = "Pictures, video and audio can't be added while editing live yet";

/// Which table an id is in.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Class {
    Free,
    Local,
    History,
    NotYet,
    Media,
}

/// The table `id` is in; an unknown id is [`Class::NotYet`].
#[must_use]
pub fn class(id: &str) -> Class {
    if FREE.binary_search(&id).is_ok() {
        Class::Free
    } else if LOCAL.binary_search(&id).is_ok() {
        Class::Local
    } else if HISTORY.binary_search(&id).is_ok() {
        Class::History
    } else if MEDIA.binary_search(&id).is_ok() {
        Class::Media
    } else {
        Class::NotYet
    }
}

/// How many tables hold `id` (a test wants exactly one).
#[must_use]
pub fn tables_holding(id: &str) -> usize {
    [FREE, LOCAL, HISTORY, NOT_YET, MEDIA].iter().filter(|t| t.binary_search(&id).is_ok()).count()
}

/// Every table, for the classification test.
#[must_use]
pub fn tables() -> [&'static [&'static str]; 5] {
    [FREE, LOCAL, HISTORY, NOT_YET, MEDIA]
}

